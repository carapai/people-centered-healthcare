//! The PKI end to end (lan-security.md; ADRs 0008, 0058; testing.md § Security): what each tier
//! issues, the constraints that bound a compromised key, and revocation reaching verifiers.

use std::net::IpAddr;

use health_pki::{
    Authority, Error, FACILITY_YEARS, Facility, ISSUING_CA_YEARS, IssuingCa, KeyPair, LEAF_DAYS,
    ROOT_YEARS, Reason, Revocations, Tier, Trust, new_key, request,
};
use health_time::{SignedDuration, Timestamp};
use rcgen::{
    BasicConstraints, CertificateParams, ExtendedKeyUsagePurpose, IsCa, Issuer, KeyUsagePurpose,
};
use x509_parser::extensions::{GeneralName, ParsedExtension};
use x509_parser::prelude::X509Certificate;

const NODE: &str = "ug-kla-0001";
const SUFFIX: &str = "facilities.health.go.ug";
const FACILITY_NAME: &str = "mulago.facilities.health.go.ug";

fn at() -> Timestamp {
    Timestamp::from_second(1_793_610_000).expect("2026-11-02")
}

fn days(n: i64) -> SignedDuration {
    SignedDuration::from_hours(24 * n)
}

/// The four tiers, each CA's key generated by its holder and certified from a request.
struct Pki {
    root: Authority,
    issuing: Authority,
    facility: Authority,
    facility_key: KeyPair,
    issuing_key: KeyPair,
    facility_serial: health_pki::Serial,
    issuing_serial: health_pki::Serial,
}

fn pki() -> Pki {
    let root = Authority::root("Uganda Health Root CA", at()).expect("root");
    let issuing_key = new_key().expect("key");
    let issued = root
        .issue_issuing_ca(
            &request(&issuing_key, "ignored").expect("request"),
            &IssuingCa {
                common_name: "Uganda Facility Issuing CA 1".into(),
                dns_suffixes: vec![SUFFIX.into()],
            },
            at(),
        )
        .expect("issuing CA");
    let issuing =
        Authority::from_pem(&issued.pem(), &issuing_key.serialize_pem()).expect("issuing CA");
    let facility_key = new_key().expect("key");
    let facility_issued = issuing
        .issue_facility(
            &request(&facility_key, "ignored").expect("request"),
            &Facility {
                node_id: NODE.into(),
                dns_names: vec![FACILITY_NAME.into()],
            },
            at(),
        )
        .expect("facility");
    let facility = Authority::from_pem(&facility_issued.pem(), &facility_key.serialize_pem())
        .expect("facility");
    Pki {
        root,
        issuing,
        facility,
        facility_key,
        issuing_key,
        facility_serial: facility_issued.serial,
        issuing_serial: issued.serial,
    }
}

impl Pki {
    fn trust(&self) -> Trust {
        Trust::new(&self.root.certificate_pem()).expect("trust")
    }

    /// A leaf for the node's names and address, as the chain the edge serves.
    fn chain(&self) -> String {
        let leaf = self
            .facility
            .issue_server(
                &new_key().expect("key"),
                &[format!("{NODE}.local"), FACILITY_NAME.into()],
                &["192.168.1.10".parse().expect("ip")],
                at(),
            )
            .expect("leaf");
        self.served(&leaf.pem())
    }

    fn served(&self, leaf: &str) -> String {
        format!(
            "{leaf}{}{}",
            self.facility.certificate_pem(),
            self.issuing.certificate_pem()
        )
    }
}

/// A leaf for `names` and `addresses` signed with `key`, bypassing every check `Authority`
/// makes: what a stolen CA key could produce.
fn forged_leaf(issuer: &Authority, key: &KeyPair, names: &[&str], addresses: &[&str]) -> String {
    let mut params = CertificateParams::new(
        names
            .iter()
            .chain(addresses)
            .map(|s| (*s).to_owned())
            .collect::<Vec<_>>(),
    )
    .expect("params");
    params.not_before =
        time::OffsetDateTime::from_unix_timestamp(at().as_second() - 60).expect("time");
    params.not_after = params.not_before + time::Duration::days(30);
    params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ServerAuth];
    let issuer = Issuer::from_ca_cert_der(issuer.certificate(), key).expect("issuer");
    params
        .signed_by(&new_key().expect("key"), &issuer)
        .expect("forged")
        .pem()
}

fn parse(der: &[u8]) -> X509Certificate<'_> {
    x509_parser::parse_x509_certificate(der).expect("x509").1
}

fn path_length(cert: &X509Certificate<'_>) -> (bool, Option<u32>) {
    let bc = cert
        .basic_constraints()
        .expect("bc")
        .expect("present")
        .value;
    (bc.ca, bc.path_len_constraint)
}

fn permitted(cert: &X509Certificate<'_>) -> (Vec<String>, Vec<Vec<u8>>) {
    let nc = cert.name_constraints().expect("nc").expect("present").value;
    assert!(nc.excluded_subtrees.is_none());
    let mut dns = Vec::new();
    let mut ips = Vec::new();
    for subtree in nc.permitted_subtrees.as_ref().expect("permitted") {
        match subtree.base {
            GeneralName::DNSName(name) => dns.push(name.to_owned()),
            GeneralName::IPAddress(bytes) => ips.push(bytes.to_vec()),
            ref other => panic!("unexpected subtree {other:?}"),
        }
    }
    (dns, ips)
}

fn lifetime_days(cert: &X509Certificate<'_>) -> i64 {
    (cert.validity().not_after.timestamp() - cert.validity().not_before.timestamp()) / 86_400
}

#[test]
fn the_edge_chain_verifies_for_its_names_and_address() {
    let pki = pki();
    let trust = pki.trust();
    let chain = pki.chain();
    for name in [&format!("{NODE}.local"), FACILITY_NAME, "192.168.1.10"] {
        trust.verify_server(&chain, name, at()).expect(name);
    }
    // A name the leaf does not carry, and an expired leaf.
    assert!(trust.verify_server(&chain, "other.local", at()).is_err());
    let expired = at() + days(LEAF_DAYS + 1);
    assert!(trust.verify_server(&chain, FACILITY_NAME, expired).is_err());
}

#[test]
fn intermediates_carry_their_constraints_and_ekus() {
    let pki = pki();
    let private: Vec<Vec<u8>> = vec![
        vec![10, 0, 0, 0, 255, 0, 0, 0],
        vec![172, 16, 0, 0, 255, 240, 0, 0],
        vec![192, 168, 0, 0, 255, 255, 0, 0],
        [[0xfc].as_slice(), &[0; 15], &[0xfe], &[0; 15]].concat(),
    ];

    let root = parse(pki.root.certificate());
    assert_eq!(path_length(&root), (true, Some(2)));
    assert!(root.name_constraints().expect("nc").is_none());
    assert!(lifetime_days(&root) >= i64::from(ROOT_YEARS) * 365);

    let issuing = parse(pki.issuing.certificate());
    assert_eq!(path_length(&issuing), (true, Some(1)));
    assert_eq!(
        permitted(&issuing),
        (vec!["local".into(), SUFFIX.into()], private.clone())
    );
    assert!(lifetime_days(&issuing) >= i64::from(ISSUING_CA_YEARS) * 365);

    let facility = parse(pki.facility.certificate());
    assert_eq!(path_length(&facility), (true, Some(0)));
    assert_eq!(
        permitted(&facility),
        (vec![format!("{NODE}.local"), FACILITY_NAME.into()], private)
    );
    let years = lifetime_days(&facility);
    assert!((i64::from(FACILITY_YEARS) * 365..=i64::from(FACILITY_YEARS) * 366).contains(&years));

    for cert in [&issuing, &facility] {
        let eku = cert
            .extended_key_usage()
            .expect("eku")
            .expect("present")
            .value;
        assert!(eku.server_auth);
        assert!(!eku.any && !eku.client_auth && !eku.code_signing && eku.other.is_empty());
        let ku = cert.key_usage().expect("ku").expect("present").value;
        assert!(ku.key_cert_sign() && !ku.digital_signature());
    }
}

#[test]
fn a_request_cannot_ask_for_more_than_its_issuer_gives() {
    let pki = pki();
    let key = new_key().expect("key");
    let mut asked = CertificateParams::new(vec!["www.google.com".to_owned()]).expect("params");
    asked.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
    asked.key_usages = vec![KeyUsagePurpose::KeyCertSign];
    let greedy = asked
        .serialize_request(&key)
        .expect("csr")
        .pem()
        .expect("pem");
    let issued = pki
        .issuing
        .issue_facility(
            &greedy,
            &Facility {
                node_id: "ug-kla-0002".into(),
                dns_names: Vec::new(),
            },
            at(),
        )
        .expect("issued");
    let cert = parse(&issued.certificate);
    assert_eq!(path_length(&cert), (true, Some(0)));
    assert!(cert.subject_alternative_name().expect("san").is_none());
    assert_eq!(permitted(&cert).0, vec!["ug-kla-0002.local".to_owned()]);
    assert!(cert.extensions().iter().all(|e| !matches!(
        e.parsed_extension(),
        ParsedExtension::SubjectAlternativeName(_)
    )));
}

#[test]
fn a_stolen_facility_key_cannot_mint_other_names_or_cas() {
    let pki = pki();
    let trust = pki.trust();

    // Authority refuses up front.
    let key = new_key().expect("key");
    for (names, addresses) in [
        (vec!["ug-kla-0002.local".to_owned()], vec![]),
        (vec!["www.google.com".to_owned()], vec![]),
        (
            vec![format!("{NODE}.local")],
            vec!["8.8.8.8".parse::<IpAddr>().expect("ip")],
        ),
    ] {
        assert!(matches!(
            pki.facility.issue_server(&key, &names, &addresses, at()),
            Err(Error::Refused(_))
        ));
    }

    // And a verifier rejects what the stolen key signs anyway.
    for (names, addresses, check) in [
        (vec!["ug-kla-0002.local"], vec![], "ug-kla-0002.local"),
        (vec!["www.google.com"], vec![], "www.google.com"),
        (vec![], vec!["8.8.8.8"], "8.8.8.8"),
    ] {
        let leaf = forged_leaf(&pki.facility, &pki.facility_key, &names, &addresses);
        assert!(
            matches!(
                trust.verify_server(&pki.served(&leaf), check, at()),
                Err(Error::Untrusted(webpki::Error::NameConstraintViolation))
            ),
            "{check}"
        );
    }

    // A sub-CA under the facility intermediate breaks its path length.
    let mut sub = CertificateParams::new(Vec::<String>::new()).expect("params");
    sub.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
    sub.key_usages = vec![KeyUsagePurpose::KeyCertSign];
    sub.not_before =
        time::OffsetDateTime::from_unix_timestamp(at().as_second() - 60).expect("time");
    sub.not_after = sub.not_before + time::Duration::days(30);
    let sub_key = new_key().expect("key");
    let facility_issuer =
        Issuer::from_ca_cert_der(pki.facility.certificate(), &pki.facility_key).expect("issuer");
    let sub_cert = sub.signed_by(&sub_key, &facility_issuer).expect("sub-CA");
    let sub_ca = Authority::from_pem(&sub_cert.pem(), &sub_key.serialize_pem());
    assert!(
        matches!(sub_ca, Err(Error::Refused(_))),
        "unconstrained CAs are refused"
    );
    let mut leaf = CertificateParams::new(vec![format!("{NODE}.local")]).expect("params");
    leaf.not_before = sub.not_before;
    leaf.not_after = sub.not_after;
    let sub_issuer = Issuer::from_ca_cert_der(sub_cert.der(), &sub_key).expect("issuer");
    let leaf = leaf
        .signed_by(&new_key().expect("key"), &sub_issuer)
        .expect("leaf");
    let chain = format!("{}{}", leaf.pem(), sub_cert.pem()) + &pki.served("");
    assert!(matches!(
        trust.verify_server(&chain, &format!("{NODE}.local"), at()),
        Err(Error::Untrusted(webpki::Error::PathLenConstraintViolated))
    ));
}

#[test]
fn a_stolen_issuing_ca_key_cannot_mint_public_names() {
    let pki = pki();
    let trust = pki.trust();
    let outside = Facility {
        node_id: "ug-kla-0002".into(),
        dns_names: vec!["mulago.example.com".into()],
    };
    let csr = request(&new_key().expect("key"), "x").expect("csr");
    assert!(matches!(
        pki.issuing.issue_facility(&csr, &outside, at()),
        Err(Error::Refused(_))
    ));
    let leaf = forged_leaf(&pki.issuing, &pki.issuing_key, &["www.google.com"], &[]);
    let chain = format!("{leaf}{}", pki.issuing.certificate_pem());
    assert!(matches!(
        trust.verify_server(&chain, "www.google.com", at()),
        Err(Error::Untrusted(webpki::Error::NameConstraintViolation))
    ));
    // The same key minting inside its constraints verifies: the constraints are what stop it.
    let leaf = forged_leaf(&pki.issuing, &pki.issuing_key, &["any.local"], &[]);
    let chain = format!("{leaf}{}", pki.issuing.certificate_pem());
    trust
        .verify_server(&chain, "any.local", at())
        .expect("inside");
}

#[test]
fn each_tier_issues_only_its_own() {
    let pki = pki();
    let csr = request(&new_key().expect("key"), "x").expect("csr");
    let facility = Facility {
        node_id: "ug-kla-0002".into(),
        dns_names: Vec::new(),
    };
    let ca = IssuingCa {
        common_name: "x".into(),
        dns_suffixes: Vec::new(),
    };
    assert!(matches!(
        pki.root.issue_facility(&csr, &facility, at()),
        Err(Error::Refused(_))
    ));
    assert!(matches!(
        pki.issuing.issue_issuing_ca(&csr, &ca, at()),
        Err(Error::Refused(_))
    ));
    assert!(matches!(
        pki.issuing.issue_publication(&csr, "x", at()),
        Err(Error::Refused(_))
    ));
    assert!(matches!(
        pki.facility.issue_facility(&csr, &facility, at()),
        Err(Error::Refused(_))
    ));
    assert_eq!(
        (pki.root.tier(), pki.issuing.tier(), pki.facility.tier()),
        (Tier::Root, Tier::IssuingCa, Tier::Facility)
    );
    // A certificate with someone else's key is refused.
    let wrong = new_key().expect("key").serialize_pem();
    assert!(matches!(
        Authority::from_pem(&pki.issuing.certificate_pem(), &wrong),
        Err(Error::Refused(_))
    ));
    // Node IDs and names must be plain lowercase DNS.
    for node_id in ["UG-KLA", "a.b", "", "-x"] {
        let bad = Facility {
            node_id: node_id.into(),
            dns_names: Vec::new(),
        };
        assert!(
            pki.issuing.issue_facility(&csr, &bad, at()).is_err(),
            "{node_id:?}"
        );
    }
}

#[test]
fn the_issuing_ca_stops_issuing_once_an_intermediate_would_outlive_it() {
    let pki = pki();
    let csr = request(&new_key().expect("key"), "x").expect("csr");
    let facility = Facility {
        node_id: "ug-kla-0002".into(),
        dns_names: Vec::new(),
    };
    let year = 365;
    pki.issuing
        .issue_facility(&csr, &facility, at() + days(4 * year))
        .expect("within its first five years");
    assert!(matches!(
        pki.issuing
            .issue_facility(&csr, &facility, at() + days(5 * year + 2)),
        Err(Error::Refused(_))
    ));
}

#[test]
fn publication_signing_signs_packages_only() {
    let pki = pki();
    let trust = pki.trust();
    let key = new_key().expect("key");
    let issued = pki
        .root
        .issue_publication(
            &request(&key, "x").expect("csr"),
            "Uganda Publication Signing 2026",
            at(),
        )
        .expect("publication");
    let cert = parse(&issued.certificate);
    assert_eq!(path_length(&cert), (false, None));
    let eku = cert
        .extended_key_usage()
        .expect("eku")
        .expect("present")
        .value;
    assert!(eku.code_signing && !eku.server_auth && !eku.client_auth && !eku.any);

    trust
        .verify_publisher(&issued.pem(), at())
        .expect("a publisher");
    assert!(trust.verify_server(&issued.pem(), "x.local", at()).is_err());
    // A TLS leaf is not a publisher, and the publication key is not a CA.
    let chain = pki.chain();
    assert!(trust.verify_publisher(&chain, at()).is_err());
    assert!(Authority::from_pem(&issued.pem(), &key.serialize_pem()).is_err());
}

#[test]
fn revocation_reaches_verifiers_through_crls() {
    let pki = pki();
    let chain = pki.chain();
    let name = format!("{NODE}.local");

    // The issuing CA revokes the facility intermediate; the CRL travels to the node.
    let mut issuing = Revocations::default();
    let unrelated = pki.issuing_serial.clone();
    issuing.revoke(unrelated, Reason::Superseded, at());
    let before = issuing.crl(&pki.issuing, at()).expect("crl");
    let mut trust = pki.trust();
    trust.add_crl(&before).expect("crl");
    trust
        .verify_server(&chain, &name, at())
        .expect("not revoked yet");

    issuing.revoke(pki.facility_serial.clone(), Reason::KeyCompromise, at());
    issuing.revoke(
        pki.facility_serial.clone(),
        Reason::Unspecified,
        at() + days(1),
    );
    assert_eq!(issuing.revoked.len(), 2, "revoking twice keeps the first");
    let crl = issuing.crl(&pki.issuing, at()).expect("crl");
    assert_eq!(issuing.number, 2);
    let mut trust = pki.trust();
    trust.add_crl(&crl).expect("crl");
    assert!(matches!(
        trust.verify_server(&chain, &name, at()),
        Err(Error::Untrusted(webpki::Error::CertRevoked))
    ));
    // An old CRL still counts while a node is offline.
    assert!(
        trust
            .verify_server(&chain, &name, at() + days(400))
            .is_err()
    );

    // The root revokes the issuing CA: everything under it falls.
    let mut root = Revocations::default();
    root.revoke(pki.issuing_serial.clone(), Reason::CaCompromise, at());
    let mut trust = pki.trust();
    trust
        .add_crl(&root.crl(&pki.root, at()).expect("crl"))
        .expect("crl");
    assert!(matches!(
        trust.verify_server(&chain, &name, at()),
        Err(Error::Untrusted(webpki::Error::CertRevoked))
    ));

    // The list round-trips as JSON, the form the tooling keeps it in.
    let json = serde_json::to_string(&issuing).expect("json");
    assert_eq!(
        serde_json::from_str::<Revocations>(&json).expect("json"),
        issuing
    );
    assert!(issuing.contains(&pki.facility_serial));
    // A facility intermediate publishes no CRL.
    assert!(Revocations::default().crl(&pki.facility, at()).is_err());
}

#[test]
fn a_forged_crl_fails_the_chain_rather_than_passing_it() {
    let pki = pki();
    let chain = pki.chain();
    // Another key under the same name as the issuing CA, signing an empty CRL.
    let impostor_key = new_key().expect("key");
    let impostor = pki
        .root
        .issue_issuing_ca(
            &request(&impostor_key, "x").expect("csr"),
            &IssuingCa {
                common_name: "Uganda Facility Issuing CA 1".into(),
                dns_suffixes: vec![SUFFIX.into()],
            },
            at(),
        )
        .expect("impostor");
    let impostor =
        Authority::from_pem(&impostor.pem(), &impostor_key.serialize_pem()).expect("impostor");
    let forged = Revocations::default().crl(&impostor, at()).expect("crl");
    let mut trust = pki.trust();
    trust.add_crl(&forged).expect("parses");
    assert!(matches!(
        trust.verify_server(&chain, &format!("{NODE}.local"), at()),
        Err(Error::Untrusted(
            webpki::Error::InvalidCrlSignatureForPublicKey
        ))
    ));
}

#[test]
fn a_leaf_reads_back_its_names_addresses_and_validity() {
    let pki = pki();
    let leaf = pki
        .facility
        .issue_server(
            &new_key().expect("key"),
            &[format!("{NODE}.local")],
            &[
                "192.168.1.10".parse().expect("ip"),
                "fd00::5".parse().expect("ip"),
            ],
            at(),
        )
        .expect("leaf");
    let read = health_pki::inspect(&leaf.pem()).expect("inspect");
    assert_eq!(read.dns_names, vec![format!("{NODE}.local")]);
    assert_eq!(
        read.addresses,
        vec![
            "192.168.1.10".parse::<IpAddr>().expect("ip"),
            "fd00::5".parse::<IpAddr>().expect("ip")
        ]
    );
    let lifetime = read.not_after.as_second() - read.not_before.as_second();
    assert_eq!(
        lifetime,
        health_pki::LEAF_DAYS * 86_400 + health_pki::BACKDATE_SECONDS
    );
    assert!(health_pki::inspect("not a certificate").is_err());
}
